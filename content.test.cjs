const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const read = name => fs.readFileSync(`${__dirname}/${name}`, 'utf8');
const source = ['content.js', 'settings.js'].map(read).join('\n');
const api = vm.runInNewContext(source + '\n({splitGlyphs,arrangedGlyphs,configuredText,validateSettings,backgroundGradient,defaultSettings,textPresets})');
assert.deepEqual(Array.from(api.splitGlyphs('e\u0301 か\u3099 👩‍💻\nA')), ['é', 'が', '👩‍💻', 'A']);
for (const preset of ['zhuangzi', 'english', 'japanese', 'ascii']) {
  const config = api.validateSettings({ textPreset: preset });
  assert(api.splitGlyphs(api.configuredText(config)).length > 10);
}
const custom = api.validateSettings({ textPreset: 'custom', customText: '<script> 世界 あいう ABC', accentColor: '#F08040', bgMode: 'linear' });
assert.equal(custom.accentColor, '#f08040');
assert.equal(api.configuredText(custom), '<script> 世界 あいう ABC');
assert(api.backgroundGradient(custom).startsWith('linear-gradient(135deg in oklab'));
assert(api.backgroundGradient(api.defaultSettings).startsWith('radial-gradient'));
assert.throws(() => api.validateSettings({ textPreset: 'custom', customText: ' \n\t' }));
assert.throws(() => api.validateSettings({ textPreset: 'custom', customText: 'a'.repeat(4001) }));
assert.throws(() => api.validateSettings({ textPreset: 'custom', customText: Array.from({length:513}, (_,i)=>String.fromCodePoint(0x4e00+i)).join('') }));
assert.throws(() => api.validateSettings({ textColor: 'url(https://example.com)' }));
assert.throws(() => api.validateSettings({ fontFamily: 'unknown' }));
assert.throws(() => api.validateSettings({ bgMode: 'unknown' }));
const restored = api.validateSettings(JSON.parse(JSON.stringify(custom)));
assert.equal(restored.customText, custom.customText);
assert.equal(restored.accentColor, custom.accentColor);
assert.equal(api.validateSettings({speed:1200}).speed,1200);
assert.equal(api.validateSettings({speed:1200}).textPreset,'zhuangzi');
console.log('PASS: multilingual graphemes, presets, literal custom text, gradients, full configuration roundtrip, invalid input');
const sequence = api.validateSettings({textPreset:'custom', customText:'ABBA 日本語 e\u0301 👩‍💻'});
const ordered = Array.from(api.arrangedGlyphs(sequence));
assert.deepEqual(ordered,Array.from(api.splitGlyphs(sequence.customText)));
const shuffledConfig = {...sequence,textOrder:'shuffled',shuffleSeed:12345};
const shuffled = Array.from(api.arrangedGlyphs(shuffledConfig));
assert.notDeepEqual(shuffled,ordered);
assert.deepEqual([...shuffled].sort(),[...ordered].sort());
assert.deepEqual(shuffled,Array.from(api.arrangedGlyphs(api.validateSettings(JSON.parse(JSON.stringify(shuffledConfig))))));
assert.notDeepEqual(shuffled,Array.from(api.arrangedGlyphs({...shuffledConfig,shuffleSeed:999})));
assert.throws(()=>api.validateSettings({textOrder:'invalid'}));
assert.throws(()=>api.validateSettings({shuffleSeed:-1}));
assert.throws(()=>api.validateSettings({shuffleSeed:1.2}));
console.log('PASS: ordered and seeded shuffled layouts, repeated glyphs, Unicode integrity, configuration persistence');
